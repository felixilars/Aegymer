class Ingredient {
  final String name;
  final double calories;
  final double protein;
  final double carbs;
  final double fat;
  final String category;
  final double fiber;
  final double sugar;
  final double saturatedFat;
  final double sodium;

  Ingredient({
    required this.name,
    required this.calories,
    required this.protein,
    required this.carbs,
    required this.fat,
    required this.category,
    required this.fiber,
    required this.sugar,
    required this.saturatedFat,
    required this.sodium,
  });
}